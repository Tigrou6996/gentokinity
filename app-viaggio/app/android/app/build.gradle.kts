// Chiave Google Maps: in android/local.properties (non va su git) -> MAPS_API_KEY=...
// oppure come variabile d'ambiente MAPS_API_KEY durante la build.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
val mapsApiKey: String = localProps.getProperty("MAPS_API_KEY") ?: System.getenv("MAPS_API_KEY") ?: ""

